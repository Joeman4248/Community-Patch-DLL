#!/usr/bin/env python3
"""Extract member function bodies of CvConnectionService from CvConnectionService.cpp BY NAME
(brace matching, comment/string aware) into a generated .inc file. Read-only on the source."""
import re, sys, os

FUNCS = ["CleanLuaErrorMessage", "ConvertLuaValuesInDocument", "ConvertLuaToJsonValue",
         "ConvertJsonToLuaValue", "ProcessLuaResult"]

def find_end(src, open_brace):
    """Index just past the '}' matching the '{' at open_brace; skips comments, strings, chars."""
    i, depth, n = open_brace, 0, len(src)
    while i < n:
        c = src[i]
        if src.startswith("//", i):
            i = src.find("\n", i)
            if i < 0: break
        elif src.startswith("/*", i):
            i = src.find("*/", i) + 2
            continue
        elif c in "\"'":
            q = c; i += 1
            while src[i] != q:
                i += 2 if src[i] == "\\" else 1
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise ValueError("unbalanced braces")

def extract(src, name):
    m = re.search(r"^[A-Za-z_][\w:<>\s\*&]*?\bCvConnectionService::" + name + r"\s*\(", src, re.M)
    if not m:
        raise SystemExit("extract.py: function %s not found" % name)
    ob = src.index("{", m.end())
    # the parameter list must close before the first '{' (no stray default-arg braces here)
    return src[m.start():find_end(src, ob)], src.count("\n", 0, m.start()) + 1

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    cpp = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "../../CvGameCoreDLL_Expansion2/CvConnectionService.cpp")
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "build/extracted.inc")
    src = open(cpp, encoding="utf-8", errors="replace").read()
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("// GENERATED by extract.py from CvConnectionService.cpp; do not edit.\n")
        for n in FUNCS:
            body, line = extract(src, n)
            # #line keeps sanitizer/compiler messages pointing at the real CvConnectionService.cpp lines
            f.write('\n// ---- %s ----\n#line %d "CvGameCoreDLL_Expansion2/CvConnectionService.cpp"\n%s\n' % (n, line, body))
    print("extract.py: wrote %s (%s)" % (out, ", ".join(FUNCS)))

main()
